const d = (daysOffset: number) => {
  const dt = new Date(today);
  dt.setDate(dt.getDate() + daysOffset);
  return dt.toISOString().slice(0, 10);
};

const ts = (daysOffset: number) => {
  const dt = new Date(today);
  dt.setDate(dt.getDate() + daysOffset);
  return dt.toISOString();
};

